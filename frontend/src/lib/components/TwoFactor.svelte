<script lang="ts">
	import { api } from '#lib/api';
	import Icon from '#lib/components/Icon.svelte';
	import { toasts } from '#lib/toast.svelte';

	type Step = 'loading' | 'off' | 'scan' | 'codes' | 'on';

	let step = $state<Step>('loading');
	let left = $state(0);
	let setup = $state<{ secret: string; qr_svg: string } | null>(null);
	let code = $state('');
	let codes = $state<string[]>([]);
	let asking = $state<'disable' | 'renew' | null>(null);
	let password = $state('');
	let busy = $state(false);

	async function load() {
		try {
			const status = await api.twoFactor();
			left = status.recovery_codes_left;
			step = status.enabled ? 'on' : 'off';
		} catch (e) {
			toasts.error(e);
		}
	}
	load();

	async function begin() {
		busy = true;
		try {
			setup = await api.startTwoFactor();
			code = '';
			step = 'scan';
		} catch (e) {
			toasts.error(e);
		} finally {
			busy = false;
		}
	}

	async function confirm(event: SubmitEvent) {
		event.preventDefault();
		busy = true;
		try {
			codes = (await api.confirmTwoFactor(code)).recovery_codes;
			setup = null;
			step = 'codes';
		} catch (e) {
			toasts.error(e);
		} finally {
			busy = false;
		}
	}

	async function withPassword(event: SubmitEvent) {
		event.preventDefault();
		busy = true;
		try {
			if (asking === 'disable') {
				await api.disableTwoFactor(password);
				toasts.push('Two-factor sign-in is off.');
				step = 'off';
			} else {
				codes = (await api.newRecoveryCodes(password)).recovery_codes;
				step = 'codes';
			}
			asking = null;
			password = '';
		} catch (e) {
			toasts.error(e);
		} finally {
			busy = false;
		}
	}

	async function copyCodes() {
		try {
			await navigator.clipboard.writeText(codes.join('\n'));
			toasts.push('Recovery codes copied.');
		} catch {
			toasts.push('Select the codes and copy them by hand.');
		}
	}

	const download = $derived(
		`data:text/plain;charset=utf-8,${encodeURIComponent(
			`Frog recovery codes\nEach code signs you in once.\n\n${codes.join('\n')}\n`
		)}`
	);
</script>

<div class="two-factor card">
	<div class="top">
		<span class="label">
			<strong>Two-factor sign-in</strong>
			<span class="faint">
				{#if step === 'on'}
					On · {left} recovery {left === 1 ? 'code' : 'codes'} left
				{:else}
					Ask for a code from an authenticator app after your password
				{/if}
			</span>
		</span>
		{#if step === 'off'}
			<button class="btn" onclick={begin} disabled={busy}>
				<Icon name="shield" size={16} /> Turn on
			</button>
		{:else if step === 'on' && !asking}
			<div class="actions">
				<button class="btn ghost" onclick={() => (asking = 'renew')}>New recovery codes</button>
				<button class="btn" onclick={() => (asking = 'disable')}>Turn off</button>
			</div>
		{/if}
	</div>

	{#if step === 'scan' && setup}
		<form class="scan" onsubmit={confirm}>
			<div class="qr" aria-label="QR code for your authenticator app">
				<!-- Generated by this server from the secret below. -->
				<!-- eslint-disable-next-line svelte/no-at-html-tags -- an SVG this server drew, with no user input in it -->
				{@html setup.qr_svg}
			</div>
			<div class="steps">
				<p>Scan this with your authenticator app, or enter the key by hand.</p>
				<code class="secret">{setup.secret}</code>
				<label class="field">
					<span>Code from the app</span>
					<input
						class="input code"
						bind:value={code}
						inputmode="numeric"
						autocomplete="one-time-code"
						maxlength="7"
						placeholder="123456"
						required
					/>
				</label>
				<div class="actions">
					<button class="btn primary" type="submit" disabled={busy || code.trim().length < 6}>
						Turn on
					</button>
					<button class="btn ghost" type="button" onclick={() => (step = 'off')}>Cancel</button>
				</div>
			</div>
		</form>
	{/if}

	{#if step === 'codes'}
		<div class="codes">
			<p>Keep these somewhere safe. Each one signs you in once if you lose your phone.</p>
			<ol>
				{#each codes as c (c)}<li><code>{c}</code></li>{/each}
			</ol>
			<div class="actions">
				<button class="btn" onclick={copyCodes}><Icon name="copy" size={16} /> Copy</button>
				<a class="btn" href={download} download="frog-recovery-codes.txt">
					<Icon name="download" size={16} /> Download
				</a>
				<button
					class="btn primary"
					onclick={() => {
						codes = [];
						load();
					}}>Done</button
				>
			</div>
		</div>
	{/if}

	{#if asking}
		<form class="confirm" onsubmit={withPassword}>
			<label class="field">
				<span>
					{asking === 'disable'
						? 'Enter your password to turn off two-factor sign-in'
						: 'Enter your password to replace your recovery codes'}
				</span>
				<input
					class="input"
					type="password"
					bind:value={password}
					autocomplete="current-password"
					required
				/>
			</label>
			<div class="actions">
				<button class="btn primary" type="submit" disabled={busy || !password}>
					{asking === 'disable' ? 'Turn off' : 'Replace codes'}
				</button>
				<button
					class="btn ghost"
					type="button"
					onclick={() => {
						asking = null;
						password = '';
					}}>Cancel</button
				>
			</div>
		</form>
	{/if}
</div>

